package com.bookshelf.bookshelfapi.service;

import com.bookshelf.bookshelfapi.dto.CategoryResponse;
import com.bookshelf.bookshelfapi.exception.BusinessRuleException;
import com.bookshelf.bookshelfapi.exception.DuplicateResourceException;
import com.bookshelf.bookshelfapi.exception.ResourceNotFoundException;
import com.bookshelf.bookshelfapi.model.Category;
import com.bookshelf.bookshelfapi.repository.CategoryRepository;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;

import java.util.List;

// Read-only by default; methods that modify data override this with their own @Transactional
@Service
@Transactional(readOnly = true)
public class CategoryService {

    private final CategoryRepository categoryRepository;

    public CategoryService(CategoryRepository categoryRepository) {
        this.categoryRepository = categoryRepository;
    }

    public List<CategoryResponse> getAllCategories() {
        return categoryRepository.findAllWithBookCount();
    }

    public Category getCategoryById(Long id) {
        return categoryRepository.findById(id)
                .orElseThrow(() -> new ResourceNotFoundException("Category not found with id: " + id));
    }

    @Transactional
    public Category createCategory(Category category) {
        // Ids are generated by the database; an id in the request body must not overwrite an existing row
        category.setId(null);
        if (categoryRepository.existsByNameIgnoreCase(category.getName())) {
            throw new DuplicateResourceException("Category already exists: " + category.getName());
        }
        return categoryRepository.save(category);
    }

    @Transactional
    public Category updateCategory(Long id, Category updatedCategory) {
        Category category = getCategoryById(id);
        categoryRepository.findByNameIgnoreCase(updatedCategory.getName())
                .filter(existing -> !existing.getId().equals(id))
                .ifPresent(existing -> {
                    throw new DuplicateResourceException("Category already exists: " + updatedCategory.getName());
                });
        category.setName(updatedCategory.getName());
        category.setDescription(updatedCategory.getDescription());
        return categoryRepository.save(category);
    }

    @Transactional
    public void deleteCategory(Long id) {
        Category category = getCategoryById(id);
        int titles = category.getBooks().size();
        if (titles > 0) {
            throw new BusinessRuleException("Category '" + category.getName() + "' still has " + titles
                    + " title(s); move or remove them first");
        }
        categoryRepository.delete(category);
    }
}
