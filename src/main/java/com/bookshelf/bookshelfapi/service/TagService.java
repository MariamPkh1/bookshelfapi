package com.bookshelf.bookshelfapi.service;

import com.bookshelf.bookshelfapi.exception.DuplicateResourceException;
import com.bookshelf.bookshelfapi.exception.ResourceNotFoundException;
import com.bookshelf.bookshelfapi.model.Book;
import com.bookshelf.bookshelfapi.model.Tag;
import com.bookshelf.bookshelfapi.repository.TagRepository;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;

import java.util.ArrayList;
import java.util.List;

// Read-only by default; methods that modify data override this with their own @Transactional
@Service
@Transactional(readOnly = true)
public class TagService {

    private final TagRepository tagRepository;

    public TagService(TagRepository tagRepository) {
        this.tagRepository = tagRepository;
    }

    public List<Tag> getAllTags() {
        return tagRepository.findAll();
    }

    public Tag getTagById(Long id) {
        return tagRepository.findById(id)
                .orElseThrow(() -> new ResourceNotFoundException("Tag not found with id: " + id));
    }

    @Transactional
    public Tag createTag(Tag tag) {
        // Ids are generated by the database; an id in the request body must not overwrite an existing row
        tag.setId(null);
        if (tagRepository.existsByNameIgnoreCase(tag.getName())) {
            throw new DuplicateResourceException("Tag already exists: " + tag.getName());
        }
        return tagRepository.save(tag);
    }

    @Transactional
    public Tag updateTag(Long id, Tag updatedTag) {
        Tag tag = getTagById(id);
        tagRepository.findByNameIgnoreCase(updatedTag.getName())
                .filter(existing -> !existing.getId().equals(id))
                .ifPresent(existing -> {
                    throw new DuplicateResourceException("Tag already exists: " + updatedTag.getName());
                });
        tag.setName(updatedTag.getName());
        return tagRepository.save(tag);
    }

    @Transactional
    public void deleteTag(Long id) {
        Tag tag = getTagById(id);
        // Book owns the relationship, so the join-table rows must be removed from the Book side
        for (Book book : new ArrayList<>(tag.getBooks())) {
            book.removeTag(tag);
        }
        tagRepository.delete(tag);
    }
}
