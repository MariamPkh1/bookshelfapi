package com.bookshelf.bookshelfapi.service;

import com.bookshelf.bookshelfapi.exception.BusinessRuleException;
import com.bookshelf.bookshelfapi.exception.ResourceNotFoundException;
import com.bookshelf.bookshelfapi.model.Book;
import com.bookshelf.bookshelfapi.model.Category;
import com.bookshelf.bookshelfapi.model.Tag;
import com.bookshelf.bookshelfapi.repository.BookRepository;
import com.bookshelf.bookshelfapi.repository.CategoryRepository;
import com.bookshelf.bookshelfapi.repository.LoanRepository;
import com.bookshelf.bookshelfapi.repository.TagRepository;
import org.springframework.core.io.Resource;
import org.springframework.data.core.PropertyPath;
import org.springframework.stereotype.Service;
import org.springframework.data.domain.Page;
import org.springframework.data.domain.Pageable;
import org.springframework.transaction.annotation.Transactional;
import org.springframework.web.multipart.MultipartFile;

import java.math.BigDecimal;
import java.util.Collection;
import java.util.HashMap;
import java.util.List;
import java.util.Map;
import java.util.Optional;

@Service
public class BookService {

    private final BookRepository bookRepository;
    private final CategoryRepository categoryRepository;
    private final TagRepository tagRepository;
    private final LoanRepository loanRepository;
    private final FileStorageService fileStorageService;

    // Constructor injection — Spring automatically provides the dependencies
    public BookService(BookRepository bookRepository,
                       CategoryRepository categoryRepository,
                       TagRepository tagRepository,
                       LoanRepository loanRepository,
                       FileStorageService fileStorageService) {
        this.bookRepository = bookRepository;
        this.categoryRepository = categoryRepository;
        this.tagRepository = tagRepository;
        this.loanRepository = loanRepository;
        this.fileStorageService = fileStorageService;
    }

    // Null filters mean "don't filter"; text filters become "" so the query never binds nulls for them
    public Page<Book> filterBooksPaginated(String keyword, Long categoryId, String language,
                                           boolean availableOnly, Pageable pageable) {
        // @Query methods don't check sort fields up front; this throws PropertyReferenceException (a 400) for unknown ones
        pageable.getSort().forEach(order -> PropertyPath.from(order.getProperty(), Book.class));

        return bookRepository.filterBooks(
                keyword == null ? "" : keyword.trim(),
                categoryId,
                language == null ? "" : language.trim(),
                availableOnly ? 1 : 0,
                pageable);
    }

    public List<String> getLanguages() {
        return bookRepository.findAllLanguages();
    }

    // bookId -> copies currently on loan, for one page of books in a single query
    public Map<Long, Long> countCopiesOnLoan(Collection<Book> books) {
        Map<Long, Long> counts = new HashMap<>();
        if (books.isEmpty()) {
            return counts;
        }
        List<Long> ids = books.stream().map(Book::getId).toList();
        for (Object[] row : loanRepository.countActiveLoansByBook(ids)) {
            counts.put((Long) row[0], (Long) row[1]);
        }
        return counts;
    }

    public Page<Book> searchBooksPaginated(String keyword, Pageable pageable) {
        return bookRepository.findByTitleContainingIgnoreCase(keyword, pageable);
    }

    public Optional<Book> getBookById(Long id) {
        return bookRepository.findById(id);
    }

    private Book findBookOrThrow(Long id) {
        return bookRepository.findById(id)
                .orElseThrow(() -> new ResourceNotFoundException("Book not found with id: " + id));
    }

    @Transactional
    public Book createBook(Book book, Long categoryId) {
        // Ids are generated by the database; an id in the request body must not overwrite an existing row.
        // The category is only set through ?categoryId, as on update.
        book.setId(null);
        book.setCategory(null);
        if (categoryId != null) {
            Category category = categoryRepository.findById(categoryId)
                    .orElseThrow(() -> new ResourceNotFoundException("Category not found with id: " + categoryId));
            book.setCategory(category);
        }
        return bookRepository.save(book);
    }

    @Transactional
    public Book updateBook(Long id, Book updatedBook, Long categoryId) {
        Book book = findBookOrThrow(id);

        book.setTitle(updatedBook.getTitle());
        book.setAuthor(updatedBook.getAuthor());
        book.setDescription(updatedBook.getDescription());
        book.setReplacementCost(updatedBook.getReplacementCost());
        book.setCopiesAvailable(updatedBook.getCopiesAvailable());
        book.setIsbn(updatedBook.getIsbn());
        book.setLanguage(updatedBook.getLanguage());
        book.setShelfLocation(updatedBook.getShelfLocation());

        if (categoryId != null) {
            Category category = categoryRepository.findById(categoryId)
                    .orElseThrow(() -> new ResourceNotFoundException("Category not found with id: " + categoryId));
            book.setCategory(category);
        }

        return bookRepository.save(book);
    }

    @Transactional
    public void deleteBook(Long id) {
        Book book = findBookOrThrow(id);
        if (loanRepository.existsByBookIdAndReturnedAtIsNull(id)) {
            throw new BusinessRuleException("'" + book.getTitle() + "' has copies on loan; record their return before removing it");
        }
        String coverImage = book.getCoverImageFileName();
        bookRepository.delete(book);
        fileStorageService.delete(coverImage);
    }

    @Transactional
    public Book uploadCoverImage(Long id, MultipartFile file) {
        Book book = findBookOrThrow(id);
        String oldCover = book.getCoverImageFileName();

        String storedFileName = fileStorageService.storeImage(file);
        book.setCoverImageFileName(storedFileName);
        Book saved = bookRepository.save(book);

        fileStorageService.delete(oldCover);
        return saved;
    }

    @Transactional
    public Book removeCoverImage(Long id) {
        Book book = findBookOrThrow(id);
        String oldCover = book.getCoverImageFileName();
        if (oldCover == null) {
            return book;
        }

        book.setCoverImageFileName(null);
        Book saved = bookRepository.save(book);

        fileStorageService.delete(oldCover);
        return saved;
    }

    public Resource getCoverImage(Long id) {
        Book book = findBookOrThrow(id);
        if (book.getCoverImageFileName() == null) {
            throw new ResourceNotFoundException("Book with id " + id + " has no cover image");
        }
        return fileStorageService.load(book.getCoverImageFileName());
    }

    @Transactional
    public Book addTagToBook(Long bookId, Long tagId) {
        Book book = findBookOrThrow(bookId);
        Tag tag = tagRepository.findById(tagId)
                .orElseThrow(() -> new ResourceNotFoundException("Tag not found with id: " + tagId));
        book.addTag(tag);
        return bookRepository.save(book);
    }

    @Transactional
    public Book removeTagFromBook(Long bookId, Long tagId) {
        Book book = findBookOrThrow(bookId);
        Tag tag = tagRepository.findById(tagId)
                .orElseThrow(() -> new ResourceNotFoundException("Tag not found with id: " + tagId));
        book.removeTag(tag);
        return bookRepository.save(book);
    }

    public List<Book> getBooksByCategory(Long categoryId) {
        return bookRepository.findByCategoryId(categoryId);
    }

    public List<Book> getAvailableBooksByCategory(Long categoryId) {
        return bookRepository.findByCategoryIdAndCopiesAvailableGreaterThan(categoryId, 0);
    }

    public List<Book> getBooksByReplacementCost(BigDecimal min, BigDecimal max) {
        return bookRepository.findByReplacementCostRange(min, max);
    }

    public List<Book> getBooksByTag(String tagName) {
        return bookRepository.findByTagName(tagName);
    }
}
